using System.Text;
using System.Text.Json.Nodes;

namespace StaticNorth.Uhp.SchemaGen;

/// <summary>Generates the complete schema-level public transport contracts without changing the existing ergonomic API.</summary>
internal sealed class ContractGenerator(string root, JsonObject definitions)
{
    private const string Header = "// <auto-generated />\n// Pinned UHP 2026-10-19. Regenerate with eng/StaticNorth.Uhp.SchemaGen.\n#nullable enable\nusing System.Text.Json;\nusing System.Text.Json.Serialization;\n\nnamespace StaticNorth.Uhp.Core.Contracts;\n\n";
    private readonly Dictionary<string, string> _files = new(StringComparer.Ordinal);
    private readonly HashSet<string> _objects = new(StringComparer.Ordinal);

    public string ResolveType(string name, JsonObject schema) => Type(name, schema);

    public async Task GenerateAsync(bool check, CancellationToken ct)
    {
        foreach (var definition in definitions)
        {
            if (definition.Value is JsonObject schema && schema["properties"] is JsonObject)
            {
                Emit(definition.Key, schema);
            }
        }

        var context = new StringBuilder(Header);
        context.AppendLine("[JsonSourceGenerationOptions(RespectNullableAnnotations = true)]");

        foreach (var name in _objects.Order(StringComparer.Ordinal))
        {
            context.AppendLine($"[JsonSerializable(typeof({name}))]");
            context.AppendLine($"[JsonSerializable(typeof({name}[]))]");
        }

        context.AppendLine("[JsonSerializable(typeof(JsonElement))]");
        context.AppendLine("[JsonSerializable(typeof(JsonElement[]))]");
        context.AppendLine("[JsonSerializable(typeof(Dictionary<string, JsonElement>))]");
        context.AppendLine("public sealed partial class UhpContractJsonContext : JsonSerializerContext;");
        _files.Add("UhpContractJsonContext.g.cs", context.ToString());
        var output = Path.Combine(root, "src/StaticNorth.Uhp.Core/Contracts/Generated");
        Directory.CreateDirectory(output);

        foreach (var path in Directory.GetFiles(output, "*.g.cs"))
        {
            if (!_files.ContainsKey(Path.GetFileName(path)))
            {
                if (check)
                {
                    throw new InvalidOperationException("Unexpected contract output: " + path);
                }

                File.Delete(path);
            }
        }

        foreach (var (name, content) in _files)
        {
            var path = Path.Combine(output, name);

            if (check)
            {
                if (!File.Exists(path) || await File.ReadAllTextAsync(path, ct).ConfigureAwait(false) != content)
                {
                    throw new InvalidOperationException("Contract output differs: " + name);
                }
            }
            else
            {
                await File.WriteAllTextAsync(path, content, new UTF8Encoding(false), ct).ConfigureAwait(false);
            }
        }

        Console.WriteLine($"{(check ? "Verified" : "Generated")} {_objects.Count} complete schema contract types.");
    }

    private void Emit(string name, JsonObject schema)
    {
        if (!_objects.Add(name))
        {
            return;
        }

        var required = schema["required"]?.AsArray().Select(value => value!.GetValue<string>()).ToHashSet(StringComparer.Ordinal) ?? [];
        var source = new StringBuilder(Header);
        source.AppendLine($"public sealed record {name}");
        source.AppendLine("{");

        foreach (var (wireName, node) in schema["properties"]!.AsObject())
        {
            var property = node!.AsObject();
            var propertyName = Pascal(wireName);

            if (propertyName == name)
            {
                propertyName = "Is" + propertyName;
            }

            var type = Type(name + propertyName, property);
            var constant = property["const"];
            var isRequired = required.Contains(wireName) && constant is null;
            var nullable = !required.Contains(wireName) || Nullable(property);
            var defaultValue = constant is not null ? " = " + constant.ToJsonString() + ";" : "";
            source.AppendLine($"    [JsonPropertyName(\"{wireName}\")]");

            if (!required.Contains(wireName) && constant is null && wireName != "next_cursor")
            {
                source.AppendLine("    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]");
            }

            source.AppendLine($"    public {(isRequired ? "required " : "")}{type}{(nullable ? "?" : "")} {propertyName} {{ get; init; }}{defaultValue}");
            source.AppendLine();
        }

        source.AppendLine("    [JsonExtensionData]");
        source.AppendLine("    public Dictionary<string, JsonElement>? AdditionalData { get; set; }");
        source.AppendLine("}");
        _files.Add(name + ".g.cs", source.ToString());
    }

    private string Type(string name, JsonObject schema)
    {
        if (schema["$ref"] is JsonValue reference)
        {
            var target = reference.GetValue<string>().Split('/')[^1];
            var definition = definitions[target]!.AsObject();

            if (definition["properties"] is JsonObject)
            {
                Emit(target, definition);
                return target;
            }

            return Type(target, definition);
        }

        if (schema["oneOf"] is JsonArray variants)
        {
            var values = variants.Where(value => value!["type"]?.ToString() != "null").ToArray();
            return values.Length == 1 ? Type(name, values[0]!.AsObject()) : "JsonElement";
        }

        var type = schema["type"] is JsonArray types
            ? types.First(value => value!.ToString() != "null")!.ToString()
            : schema["type"]?.ToString();

        switch (type)
        {
            case "string": return "string";
            case "integer": return "long";
            case "number": return "double";
            case "boolean": return "bool";
            case "array": return Type(name + "Item", schema["items"]!.AsObject()) + "[]";
            case "object":
                if (schema["properties"] is JsonObject)
                {
                    Emit(name, schema);
                    return name;
                }

                return schema["additionalProperties"] is JsonObject additional
                    ? "Dictionary<string, " + Type(name + "Value", additional) + ">"
                    : "Dictionary<string, JsonElement>";
            default: return "JsonElement";
        }
    }

    private static bool Nullable(JsonObject schema) =>
        schema["type"] is JsonArray types && types.Any(type => type!.ToString() == "null") ||
        schema["oneOf"] is JsonArray variants && variants.Any(variant => variant!["type"]?.ToString() == "null");

    private static string Pascal(string value)
    {
        var result = new StringBuilder();
        var capitalize = true;

        foreach (var character in value)
        {
            if (!char.IsAsciiLetterOrDigit(character))
            {
                capitalize = true;
                continue;
            }

            result.Append(capitalize ? char.ToUpperInvariant(character) : character);
            capitalize = false;
        }

        return result.ToString();
    }
}
