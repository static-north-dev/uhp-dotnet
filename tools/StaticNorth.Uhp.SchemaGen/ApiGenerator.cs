using System.Text;
using System.Text.Json.Nodes;

namespace StaticNorth.Uhp.SchemaGen;

internal sealed class ApiGenerator(string root, ContractGenerator contracts)
{
    private const string Header = "// <auto-generated />\n// Pinned UHP 2026-10-19. Regenerate with tools/StaticNorth.Uhp.SchemaGen.\n#nullable enable\n";
    private static readonly HashSet<string> Existing = new(StringComparer.Ordinal)
    {
        "getDiscovery", "listHarnesses", "getHarness", "listModels", "listHarnessModels",
        "createResponse", "getResponse", "cancelResponse", "cancelSession"
    };
    private readonly List<ApiOperation> _operations = [];

    public async Task PrepareAsync(CancellationToken ct)
    {
        var api = await OpenApiReader
            .ReadAsync(Path.Combine(root, "spec/upstream/uhp-2026-10-19.openapi.yaml"), ct)
            .ConfigureAwait(false);

        foreach (var (path, node) in api["paths"]!.AsObject())
        {
            var item = node!.AsObject();

            foreach (var method in new[] { "get", "post", "put", "patch", "delete" })
            {
                if (item[method] is not JsonObject operation)
                {
                    continue;
                }

                var id = operation["operationId"]!.GetValue<string>();

                if (Existing.Contains(id))
                {
                    continue;
                }

                var name = Pascal(id);
                var parameters = new List<ApiParameter>();

                foreach (var parameter in (item["parameters"]?.AsArray() ?? []).Concat(operation["parameters"]?.AsArray() ?? []))
                {
                    var value = parameter!.AsObject();

                    if (value["$ref"] is { } reference)
                    {
                        value = api["components"]!["parameters"]![reference
                            .GetValue<string>()
                            .Split('/')[^1]]!.AsObject();
                    }

                    var location = value["in"]!.GetValue<string>();

                    if (location is not ("path" or "query"))
                    {
                        continue;
                    }

                    var wireName = value["name"]!.GetValue<string>();
                    var schema = value["schema"]?.AsObject() ?? new JsonObject { ["type"] = "string" };
                    parameters.Add(new(wireName, char.ToLowerInvariant(Pascal(wireName)[0]) + Pascal(wireName)[1..], location,
                        contracts.ResolveType(name + Pascal(wireName), schema), schema));
                }

                var query = parameters
                    .Where(parameter => parameter.Location == "query")
                    .ToArray();
                string? queryType = null;

                if (query.Length > 0)
                {
                    var properties = new JsonObject();

                    foreach (var parameter in query)
                    {
                        properties.Add(parameter.Name, parameter.Schema.DeepClone());
                    }

                    queryType = contracts.ResolveType(name + "Query", new JsonObject { ["type"] = "object", ["properties"] = properties });
                }

                var requestBody = operation["requestBody"]?.AsObject();
                var body = requestBody?["content"]?.AsObject();
                var jsonBody = body?["application/json"]?["schema"]?.AsObject();
                var requestType = jsonBody is null ? null : contracts.ResolveType(name + "Request", ConvertRef(jsonBody));
                var response = operation["responses"]!
                    .AsObject()
                    .First(pair => pair.Key.StartsWith('2')).Value!.AsObject();
                var responseContent = response["content"]?.AsObject();
                var responseSchema = responseContent?["application/json"]?["schema"]?.AsObject();
                var responseType = responseSchema is null ? null : contracts.ResolveType(name + "Response", ConvertRef(responseSchema));
                var (family, capability) = Family(path, id);
                _operations.Add(new(name, method, path, family, capability, requestType, requestBody?["required"]?.GetValue<bool>() != true,
                    responseType, body is not null && (jsonBody is null || body.Count > 1), responseContent is not null && responseSchema is null, parameters, queryType));
            }
        }

        // Sessions §6 defines this operation even though the pinned OpenAPI omits it.
        _operations.Add(new("DeleteSession", "delete", "/v1/sessions/{session_id}", "Session", "session_listing", null, false, "Deleted", false, false,
            [new("session_id", "sessionId", "path", "string", new JsonObject { ["type"] = "string" })], null));
    }

    public async Task GenerateAsync(bool check, CancellationToken ct)
    {
        var files = new Dictionary<string, string>(StringComparer.Ordinal);
        var routes = new StringBuilder(Header + "namespace StaticNorth.Uhp.Core;\n\npublic static class UhpApiRoutes\n{\n");

        foreach (var operation in _operations)
        {
            routes.AppendLine($"    public const string {operation.Name} = \"{operation.Path.TrimStart('/')}\";");
            files.Add($"src/StaticNorth.Uhp.Server/Endpoints/Generated/{operation.Name}Endpoint.g.cs", Endpoint(operation));
        }

        routes.AppendLine("}");
        files.Add("src/StaticNorth.Uhp.Core/Protocol/UhpApiRoutes.g.cs", routes.ToString());

        foreach (var family in _operations.GroupBy(operation => operation.Family))
        {
            var contract = new StringBuilder(Header + "using System.Text.Json;\nusing Wire = StaticNorth.Uhp.Core.Contracts;\n\nnamespace StaticNorth.Uhp.Server;\n\n");
            contract.AppendLine($"public interface IUhp{family.Key}Backend\n{{");

            foreach (var operation in family)
            {
                contract.AppendLine($"    {Return(operation, false)} {operation.Name}Async({string.Join(", ", Arguments(operation, false))});");
            }

            contract.AppendLine("}");
            files.Add($"src/StaticNorth.Uhp.Server/Backends/Generated/IUhp{family.Key}Backend.g.cs", contract.ToString());
            files.Add($"src/StaticNorth.Uhp.Client/Generated/UhpClient.{family.Key}.g.cs", Client(family));
        }

        foreach (var (relative, content) in files)
        {
            var path = Path.Combine(root, relative);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);

            if (check)
            {
                if (!File.Exists(path) || await File
                    .ReadAllTextAsync(path, ct)
                    .ConfigureAwait(false) != content)
                {
                    throw new InvalidOperationException("API output differs: " + relative);
                }
            }
            else
            {
                await File
                    .WriteAllTextAsync(path, content, new UTF8Encoding(false), ct)
                    .ConfigureAwait(false);
            }
        }

        Console.WriteLine($"{(check ? "Verified" : "Generated")} {_operations.Count} additional typed API operations.");
    }

    private static string Endpoint(ApiOperation operation)
    {
        var source = new StringBuilder(Header + "using System.Text.Json;\nusing Microsoft.AspNetCore.Builder;\nusing Microsoft.AspNetCore.Http;\nusing Microsoft.AspNetCore.Http.HttpResults;\nusing Microsoft.AspNetCore.Routing;\nusing StaticNorth.Valiant.Endpoints;\nusing StaticNorth.Valiant.Endpoints.AspNetCore;\nusing StaticNorth.Uhp.Core;\nusing StaticNorth.Uhp.Server.Transport;\nusing Wire = StaticNorth.Uhp.Core.Contracts;\n\nnamespace StaticNorth.Uhp.Server.Endpoints;\n\n");
        source.AppendLine($"[ValiantEndpoint<UhpEndpointGroup>]\ninternal sealed class {operation.Name}Endpoint : IEndpoint\n{{");
        var route = operation.Path.Contains("{path}", StringComparison.Ordinal)
            ? "(\"/\" + UhpApiRoutes." + operation.Name + ").Replace(\"{path}\", \"{**path}\", StringComparison.Ordinal)"
            : "\"/\" + UhpApiRoutes." + operation.Name;
        source.AppendLine($"    public static IEndpointConventionBuilder Map(IEndpointRouteBuilder builder) => builder.Map{Pascal(operation.Method)}({route}, HandleAsync);");
        source.AppendLine();
        var result = operation.BinaryResponse ? "FileStreamHttpResult" : operation.ResponseType is { } response ? "Ok<" + Qualified(response) + ">" : "NoContent";
        source.AppendLine($"    private static async Task<{result}> HandleAsync(HttpContext http, CancellationToken ct)\n    {{");
        source.AppendLine($"        var backend = UhpApiBinding.Backend<IUhp{operation.Family}Backend>(http, \"{operation.Capability}\");");

        if (operation.RequestType is { } body && !operation.BinaryRequest)
        {
            source.AppendLine($"        var request = await UhpApiBinding.ReadJsonAsync(http, (System.Text.Json.Serialization.Metadata.JsonTypeInfo<{Qualified(body)}>)Wire.UhpContractJsonContext.Default.GetTypeInfo(typeof({Qualified(body)}))!, {operation.OptionalBody
                .ToString()
                .ToLowerInvariant()}).ConfigureAwait(false);");
        }

        if (operation.BinaryRequest)
        {
            source.AppendLine("        var request = await UhpApiBinding.ReadBodyAsync(http).ConfigureAwait(false);");
        }

        if (operation.QueryType is { } query)
        {
            source.AppendLine($"        var query = new Wire.{query}\n        {{");

            foreach (var parameter in operation.Parameters.Where(parameter => parameter.Location == "query"))
            {
                var parse = parameter.Type switch { "long" => "Integer", "bool" => "Boolean", "string[]" => "Strings", "string" => "String", _ => "Json" };
                source.AppendLine($"            {Pascal(parameter.Name)} = UhpApiBinding.Query{parse}(http, \"{parameter.Name}\"),");
            }

            source.AppendLine("        };\n");
        }

        var args = operation.Parameters
            .Where(parameter => parameter.Location == "path")
            .Select(parameter => $"UhpApiBinding.Route(http, \"{parameter.Name}\")")
            .ToList();

        if (operation.RequestType is not null || operation.BinaryRequest)
        {
            args.Add("request" + (operation.RequestType is not null && !operation.BinaryRequest ? "!" : ""));
        }

        if (operation.QueryType is not null)
        {
            args.Add("query");
        }

        args.Add("UhpHttp.GetContext(http)");
        args.Add("ct");
        var call = $"await backend.{operation.Name}Async({string.Join(", ", args)}).ConfigureAwait(false)";

        if (operation.ResponseType is not null || operation.BinaryResponse)
        {
            source.AppendLine($"        var response = {call};");
            source.AppendLine(operation.BinaryResponse ? "        return UhpApiBinding.File(http, response);" : "        return TypedResults.Ok(response);");
        }
        else
        {
            source.AppendLine($"        {call};");
            source.AppendLine("        return TypedResults.NoContent();");
        }

        source.AppendLine("    }\n}");
        return source.ToString();
    }

    private static string Client(IEnumerable<ApiOperation> operations)
    {
        var source = new StringBuilder(Header + "using System.Text.Json;\nusing StaticNorth.Uhp.Core;\nusing Wire = StaticNorth.Uhp.Core.Contracts;\n\nnamespace StaticNorth.Uhp.Client;\n\npublic sealed partial class UhpClient\n{\n");

        foreach (var operation in operations)
        {
            var args = Arguments(operation, true);
            source.AppendLine($"    public {Return(operation, true)} {operation.Name}Async({string.Join(", ", args)})\n    {{");
            source.AppendLine($"        RequireCapability(\"{operation.Capability}\");");
            source.AppendLine($"        var routePath = UhpApiRoutes.{operation.Name};");

            foreach (var parameter in operation.Parameters.Where(parameter => parameter.Location == "path"))
            {
                source.AppendLine($"        routePath = routePath.Replace(\"{{{parameter.Name}}}\", Segment({parameter.Identifier}), StringComparison.Ordinal);");
            }

            if (operation.QueryType is not null)
            {
                source.AppendLine("        if (query is not null)\n        {");

                foreach (var parameter in operation.Parameters.Where(parameter => parameter.Location == "query"))
                {
                    source.AppendLine($"            routePath = AddQuery(routePath, \"{parameter.Name}\", query.{Pascal(parameter.Name)});");
                }

                source.AppendLine("        }");
            }

            var request = operation.BinaryRequest ? "request" : operation.RequestType is not null ? "ContractBody(request)" : "null";
            var method = "HttpMethod." + Pascal(operation.Method);

            if (operation.BinaryRequest || operation.BinaryResponse)
            {
                var type = operation.BinaryResponse ? "UhpDownload" : Qualified(operation.ResponseType!);
                source.AppendLine($"        return SendBinaryAsync<{type}>({method}, routePath, {request}, idempotencyKey, ct, {(operation.Name == "UploadFile")
                    .ToString()
                    .ToLowerInvariant()});");
            }
            else
            {
                var type = operation.ResponseType is { } response ? Qualified(response) : "object";
                source.AppendLine($"        return SendContractAsync<{type}>({method}, routePath, {request}, idempotencyKey, ct);");
            }

            source.AppendLine("    }\n");
        }

        source.AppendLine("}");
        return source.ToString();
    }

    private static List<string> Arguments(ApiOperation operation, bool client)
    {
        var args = operation.Parameters
            .Where(parameter => parameter.Location == "path")
            .Select(parameter => "string " + parameter.Identifier)
            .ToList();

        if (operation.BinaryRequest)
        {
            args.Add((client ? "UhpUpload" : "UhpRequestBody") + " request");
        }
        else if (operation.RequestType is { } request)
        {
            args.Add(Qualified(request) + (operation.OptionalBody ? "?" : "") + " request" + (client && operation.OptionalBody ? " = null" : ""));
        }

        if (operation.QueryType is { } query)
        {
            args.Add("Wire." + query + (client ? "? query = null" : " query"));
        }

        if (client)
        {
            args.Add("string? idempotencyKey = null");
            args.Add("CancellationToken ct = default");
        }
        else
        {
            args.Add("UhpRequestContext context");
            args.Add("CancellationToken ct");
        }

        return args;
    }

    private static string Return(ApiOperation operation, bool client) => operation.BinaryResponse
        ? "Task<" + (client ? "UhpDownload" : "UhpBinaryContent") + ">"
        : operation.ResponseType is { } type ? "Task<" + Qualified(type) + ">" : "Task";

    private static string Qualified(string type) => type.StartsWith("Dictionary<", StringComparison.Ordinal) || type.StartsWith("JsonElement", StringComparison.Ordinal) || type is "string" or "long" or "bool" ? type : "Wire." + type;

    private static JsonObject ConvertRef(JsonObject schema)
    {
        var copy = (JsonObject)schema.DeepClone();

        if (copy["$ref"] is { } reference)
        {
            copy["$ref"] = reference
                .GetValue<string>()
                .Replace("#/components/schemas/", "#/$defs/", StringComparison.Ordinal);
        }

        return copy;
    }

    private static (string, string) Family(string path, string id)
    {
        if (path.Contains("/memories", StringComparison.Ordinal)) { return ("Memory", "memories"); }
        if (path.StartsWith("/v1/environments", StringComparison.Ordinal)) { return ("Environment", "environments"); }
        if (path.Contains("/skills/", StringComparison.Ordinal)) { return ("HarnessManagement", "harness_management"); }
        if (path.Contains("/plugins/", StringComparison.Ordinal) || path.EndsWith("/plugin", StringComparison.Ordinal)) { return ("Plugin", "plugins"); }
        if (path.EndsWith("/share", StringComparison.Ordinal)) { return ("Sharing", "session_sharing"); }
        if (path.Contains("/files", StringComparison.Ordinal) || path.StartsWith("/v1/containers", StringComparison.Ordinal)) { return ("File", id == "uploadFile" ? "files_input" : "files_output"); }
        if (path.StartsWith("/v1/sessions", StringComparison.Ordinal)) { return ("Session", "session_listing"); }
        if (path.StartsWith("/v1/harnesses", StringComparison.Ordinal)) { return ("HarnessManagement", "harness_management"); }
        return ("ResponseStorage", "");
    }

    private static string Pascal(string value) => string.Concat(value
        .Split('_')
        .Select(part => char.ToUpperInvariant(part[0]) + part[1..]));
}
